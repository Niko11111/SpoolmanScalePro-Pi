#!/usr/bin/env python3
"""Writes static/js/icon_data.js: the button icons, taken from the Lucide
catalog on this Mac. Runs on the Mac only; the Pi gets the generated file.

The catalog is the one TheRentalScale uses (Lucide, pinned, about 1,500
icons): ~/.trs/icons/lucide-<version>/icons/<name>.svg. Only the icons in
ICONS ship, so the page needs no CDN and works offline (the fair kit).

A new icon: pick it in the catalog (its index.html searches by name), add a
line to ICONS, run `python3 tools/build_icons.py`, then map the button's
text key to it in ACTION_ICONS (static/js/icons.js).

Downloaded SVGs are not trusted: only drawing elements and their geometry
survive, and the page builds them with createElementNS, never innerHTML.
"""

import json
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

LUCIDE_VERSION = "0.460.0"
CATALOG = Path.home() / ".trs" / "icons" / f"lucide-{LUCIDE_VERSION}"
OUT = Path(__file__).resolve().parent.parent / "static" / "js" / "icon_data.js"

# Name in this project -> Lucide name. The name says what the icon MEANS;
# where TheRentalScale has the same meaning, it is the same name and icon.
ICONS = {
    "ok": "check",
    "close": "x",
    "delete": "trash-2",
    "undo": "undo-2",
    "download": "download",
    "upload": "upload",
    "archive": "archive",
    "update": "cloud-download",
    "refresh": "refresh-cw",
    "search": "search",
    "network": "wifi",
    "hotspot_on": "radio-tower",
    "hotspot_off": "wifi-off",
    "keyboard": "keyboard",
    "pin": "pin",
    "copy": "copy",
    "link": "link",
    "key": "key-round",
    "send": "send",
    "external": "external-link",
    "locks": "lock",
    "unlocked": "lock-open",
    "login": "log-in",
    "reboot": "rotate-cw",
    "power": "power",
    "play": "play",
    "stop": "square",
    "switch": "arrow-left-right",
    "scale": "scale",
    "file": "file-text",
    "info": "info",
    "clock": "clock",
    "plug": "plug",
    "unplug": "unplug",
    "back": "chevron-left",
    "next": "chevron-right",
    "expand": "chevron-down",
    "collapse": "chevron-up",
    "skip": "skip-forward",
    "home": "house",
    "wizard": "wand-sparkles",
    "daily": "flask-conical",
}

SVG_NS = "{http://www.w3.org/2000/svg}"
DRAWING = {
    "path": ("d",),
    "line": ("x1", "y1", "x2", "y2"),
    "circle": ("cx", "cy", "r"),
    "ellipse": ("cx", "cy", "rx", "ry"),
    "rect": ("x", "y", "width", "height", "rx", "ry"),
    "polyline": ("points",),
    "polygon": ("points",),
}
# Geometry is numbers and path commands; anything else is dropped. A few
# shapes are filled dots (the key's eye): fill, with these values only.
SAFE_CHARS = set("0123456789.,- MmLlHhVvCcSsQqTtAaZze")
SAFE_FILLS = ("currentColor", "none")


def keep(tag: str, name: str, value: str) -> bool:
    if name == "fill":
        return value in SAFE_FILLS
    return name in DRAWING[tag] and set(value) <= SAFE_CHARS


def drawing(svg_text: str) -> list:
    """[[tag, {attribute: value}], ...] for the drawing elements of one SVG."""
    shapes = []
    for element in ET.fromstring(svg_text):
        tag = element.tag.removeprefix(SVG_NS)
        if tag not in DRAWING:
            continue
        attrs = {k: v for k, v in element.attrib.items() if keep(tag, k, v)}
        shapes.append([tag, attrs])
    return shapes


def license_text() -> str:
    return (CATALOG / "LICENSE").read_text().strip()


def build() -> dict:
    data = {}
    for name, lucide in ICONS.items():
        try:
            data[name] = drawing((CATALOG / "icons" / f"{lucide}.svg").read_text())
        except (OSError, ET.ParseError) as e:
            sys.exit(f"build_icons: {name} (Lucide '{lucide}') not in the catalog or unreadable: {e}")
    return data


def write(data: dict) -> None:
    notice = "\n".join(" * " + line if line else " *" for line in license_text().splitlines())
    lines = ["/* SpoolmanScale Pro - button icons. GENERATED by tools/build_icons.py,",
             " * do not edit by hand. Read only through SSPro.icon (icons.js).",
             f" * Icons: Lucide {LUCIDE_VERSION}, https://lucide.dev, under this license:",
             " *", notice, " */", "SSPro.iconData = {"]
    lines += [f"  {json.dumps(name)}: {json.dumps(shapes)}," for name, shapes in data.items()]
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n")


def main() -> None:
    if not CATALOG.is_dir():
        sys.exit(f"build_icons: no Lucide catalog at {CATALOG} (TheRentalScale's tools/icon_catalog.py fetches it)")
    write(build())
    print(f"build_icons: {len(ICONS)} icons -> {OUT}")


if __name__ == "__main__":
    main()
